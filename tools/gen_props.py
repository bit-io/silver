def main():
    props = open(os.path.join(HERE, "css_properties.txt")).read().split()
    tab = {}
    for names, inh, init, gram in G:
        for n in names:
            tab[n] = (inh, init, gram)
    miss = [p for p in props if p not in tab]
    extra = [p for p in tab if p not in props]
    if miss: print("BRAK W TABELI:", " ".join(miss)); sys.exit(1)
    if extra: print("UWAGA nadmiarowe:", " ".join(extra))
    rows = []
    for p in sorted(tab):
        inh, init, gram = tab[p]
        rows.append("%s\x01%d\x01%s\x01%s" % (p, inh, init, gram))
    # tabela jako kilka literałów (H# nie ma literałów wielowierszowych) składanych w funkcjach
    chunks = []
    cur = []
    size = 0
    for r in rows:
        r2 = r.replace("\\", "\\\\").replace('"', '\\"').replace("\x01", "\\u0001")
        cur.append(r2); size += len(r2)
        if size > 3500: chunks.append(cur); cur = []; size = 0
    if cur: chunks.append(cur)
    out = []
    out.append(";; AUTOMATYCZNIE WYGENEROWANE przez tools/gen_props.py — nie edytuj ręcznie.")
    out.append(";; Tabela właściwości CSS: nazwa \\u0001 dziedziczona \\u0001 wartość początkowa \\u0001 gramatyka, rekordy rozdzielone \\u0002.")
    out.append("")
    for i, ch in enumerate(chunks):
        out.append("fn table_%d() -> string is" % i)
        out.append('    return "\\u0002" + "' + '\\u0002" + "'.join(ch) + '\\u0002"')
        out.append("end")
        out.append("")
    out.append("pub fn table() -> string is")
    out.append("    return " + " + ".join("table_%d()" % i for i in range(len(chunks))))
    out.append("end")
    out.append("")
    out.append("pub fn count() -> int is return %d end" % len(tab))
    dst = os.path.join(HERE, "..", "src", "engine", "props_data.h#")
    open(dst, "w").write("\n".join(out) + "\n")
    print("OK: %d właściwości, %d bloków -> %s" % (len(tab), len(chunks), os.path.normpath(dst)))
main()
